export function seedCatalog() {
  return {
    theories: SEED_THEORIES.map(({ items, ...t }, sortOrder) => ({
      ...t,
      sortOrder,
    })),
    items: SEED_THEORIES.flatMap((t) =>
      t.items.map((q, i) => ({
        ...q,
        theoryId: t.id,
        lessonIds: t.lessonIds,
        sortOrder: i,
        deleted: false,
        revision: 1,
      })),
    ),
    orders: [],
  };
}
