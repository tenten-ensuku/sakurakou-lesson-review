function theory(
  id,
  title,
  category,
  canonical,
  conditions,
  exceptions,
  sourceUrl,
  lessonIds,
  cardKeys,
  question,
  choices,
  correctIndex,
  cloze,
  clozeChoices,
  clozeCorrect,
) {
  return {
    id: "theory-" + id,
    title,
    category,
    canonical,
    conditions,
    exceptions,
    sourceUrl,
    sourceLabel:
      sourceUrl === J
        ? "基本序列"
        : sourceUrl === T
          ? "セオリー集"
          : "一向聴（基礎講義）",
    lessonIds,
    cardKeys,
    deleted: false,
    items: [
      {
        id: "check-" + id + "-choice",
        type: "choice",
        question,
        choices,
        correctIndex,
        explanation: canonical + "\n" + conditions + "\n" + exceptions,
      },
      {
        id: "check-" + id + "-cloze",
        type: "cloze",
        question: cloze,
        choices: clozeChoices,
        correctIndex: clozeCorrect,
        explanation: canonical + "\n" + conditions + "\n" + exceptions,
      },
    ],
  };
}
